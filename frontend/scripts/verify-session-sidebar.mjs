import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(process.argv[2]);
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.setDefaultTimeout(10000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const sidebar = page.locator('.session-sidebar');
const opacity = async locator => locator.evaluate(element => getComputedStyle(element).opacity);
try {
  await page.goto('http://127.0.0.1:5173/');
  assert.equal(await sidebar.locator('.session-new-button').count(), 0);
  await sidebar.getByRole('button', { name: '新建独立会话', exact: true }).click();
  await page.getByRole('heading', { name: '新会话', exact: true }).waitFor();
  const independentUrl = page.url();
  await sidebar.getByRole('button', { name: '新建项目', exact: true }).click();
  await page.getByRole('dialog', { name: '新建项目' }).getByRole('textbox').fill('侧栏验收项目');
  await page.getByRole('button', { name: '创建项目', exact: true }).click();
  await sidebar.getByRole('button', { name: '在侧栏验收项目中新建会话', exact: true }).click();
  await page.waitForURL(url => url.href !== independentUrl && url.pathname.startsWith('/sessions/'));
  await page.getByRole('heading', { name: '新会话', exact: true }).waitFor();
  assert.equal(await sidebar.locator('.session-recent-list .session-nav-row').count(), 1);
  assert.equal(await sidebar.locator('.session-group-children .session-nav-row').count(), 1);
  const row = sidebar.locator('.session-group-children .session-nav-row');
  const actions = row.locator('.session-row-actions');
  await page.getByRole('heading', { name: '新会话', exact: true }).hover();
  assert.equal(await opacity(actions), '0');
  await row.hover();
  assert.equal(await opacity(actions), '1');
  await row.getByRole('button', { name: '重命名会话新会话', exact: true }).click();
  await page.getByRole('dialog', { name: '重命名会话' }).getByRole('textbox').fill('项目内专属会话');
  await page.getByRole('dialog', { name: '重命名会话' }).getByRole('button', { name: '保 存', exact: true }).click();
  await page.getByRole('heading', { name: '项目内专属会话', exact: true }).waitFor();
  await page.reload();
  await sidebar.getByRole('button', { name: '项目内专属会话', exact: true }).waitFor();
  assert.equal(await sidebar.locator('.session-recent-list').getByRole('button', { name: '项目内专属会话', exact: true }).count(), 0);
  await row.hover();
  await row.getByRole('button', { name: '归档会话项目内专属会话', exact: true }).click();
  assert.equal(await sidebar.getByRole('button', { name: '项目内专属会话', exact: true }).count(), 0);
  await sidebar.getByRole('button', { name: /已归档$/ }).click();
  const archived = sidebar.locator('.session-nav-row').filter({ hasText: '项目内专属会话' });
  await archived.hover();
  await archived.getByRole('button', { name: '恢复会话项目内专属会话', exact: true }).click();
  await sidebar.getByRole('button', { name: /返回最近会话$/ }).click();
  const project = sidebar.locator('.session-project-heading').filter({ hasText: '侧栏验收项目' });
  await page.getByRole('heading', { name: '项目内专属会话', exact: true }).hover();
  assert.equal(await opacity(project.locator('.session-row-actions')), '0');
  await project.hover();
  await project.getByRole('button', { name: '重命名项目侧栏验收项目', exact: true }).click();
  await page.getByRole('dialog', { name: '重命名项目' }).getByRole('textbox').fill('重命名验收项目');
  await page.getByRole('dialog', { name: '重命名项目' }).getByRole('button', { name: '保 存', exact: true }).click();
  const renamedProject = sidebar.locator('.session-project-heading').filter({ hasText: '重命名验收项目' });
  await renamedProject.hover();
  await renamedProject.getByRole('button', { name: '归档项目重命名验收项目', exact: true }).click();
  assert.equal(await sidebar.getByRole('button', { name: '项目内专属会话', exact: true }).count(), 0);
  assert.equal(await sidebar.locator('.session-recent-list .session-nav-row').count(), 1);
  await sidebar.getByRole('button', { name: /已归档$/ }).click();
  await renamedProject.hover();
  await renamedProject.getByRole('button', { name: '恢复项目重命名验收项目', exact: true }).click();
  await sidebar.getByRole('button', { name: /返回最近会话$/ }).click();
  await sidebar.locator('.session-group-children .session-nav-row').hover();
  await sidebar.getByRole('button', { name: '删除会话项目内专属会话', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '删 除', exact: true }).click();
  await page.getByRole('heading', { name: '从一项工作开始' }).waitFor();
  await renamedProject.hover();
  await renamedProject.getByRole('button', { name: '删除项目重命名验收项目', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '删 除', exact: true }).click();
  await page.reload();
  assert.equal(await sidebar.getByRole('button', { name: '项目内专属会话', exact: true }).count(), 0);
  assert.equal(await sidebar.locator('.session-project-heading').count(), 0);
  assert.equal(await sidebar.locator('.session-recent-list .session-nav-row').count(), 1);
  assert.deepEqual(errors, []);
  console.log('PASS: separate independent/project lists, section add button, hover-only actions, session/project rename, archive/restore, delete and refresh; no page errors.');
} finally { await browser.close(); }
